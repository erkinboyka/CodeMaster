<?php

namespace Database\Seeders;

use Illuminate\Database\Seeder;
use App\Models\Problem;
use App\Models\ProblemTopic;

class ProblemSeeder extends Seeder
{
    public function run(): void
    {
        Problem::query()->delete();
        ProblemTopic::query()->delete();

        $topics = [
            'Array', 'String', 'Hash Table', 'Dynamic Programming', 'Math',
            'Sorting', 'Greedy', 'Binary Search', 'Tree', 'Graph',
            'Stack', 'Queue', 'Linked List', 'Recursion', 'Bit Manipulation',
            'Two Pointers', 'Sliding Window', 'Backtracking', 'Heap', 'Trie',
            'Matrix', 'BFS', 'DFS', 'Divide and Conquer', 'Prefix Sum',
            'Union Find', 'Monotonic Stack', 'Design', 'Counting', 'Simulation',
        ];

        $topicModels = [];
        foreach ($topics as $name) {
            $topicModels[$name] = ProblemTopic::create([
                'name' => $name,
                'slug' => \Illuminate\Support\Str::slug($name),
            ]);
        }

        $problems = $this->getEasyProblems();
        $problems = array_merge($problems, $this->getMediumProblems());
        $problems = array_merge($problems, $this->getHardProblems());

        foreach ($problems as $data) {
            $topicNames = $data['topics'];
            unset($data['topics']);

            $data['slug'] = \Illuminate\Support\Str::slug($data['title']);
            $problem = Problem::create($data);

            foreach ($topicNames as $topicName) {
                if (isset($topicModels[$topicName])) {
                    $problem->topics()->attach($topicModels[$topicName]->id);
                }
            }
        }

        ProblemTopic::each(function ($topic) {
            $topic->update(['problems_count' => $topic->problems()->count()]);
        });
    }

